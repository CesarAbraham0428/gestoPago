-- Catálogos de países, nacionalidades y ocupaciones. Clientes y domicilios los referencian por nombre.
CREATE TABLE paises (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    CONSTRAINT uq_paises_nombre UNIQUE (nombre),
    CONSTRAINT ck_paises_nombre CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE nacionalidades (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    pais_id integer NOT NULL REFERENCES paises (id),
    CONSTRAINT uq_nacionalidades_nombre UNIQUE (nombre),
    CONSTRAINT ck_nacionalidades_nombre CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE ocupaciones (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre varchar(50) NOT NULL,
    CONSTRAINT uq_ocupaciones_nombre UNIQUE (nombre),
    CONSTRAINT ck_ocupaciones_nombre CHECK (length(btrim(nombre)) > 0)
);

