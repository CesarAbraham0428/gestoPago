-- Datos anteriores al catálogo: se corrigen mayúsculas y acentos ("Mexico" -> "México") cuando coinciden.
UPDATE domicilios d SET pais = c.nombre FROM paises c
WHERE d.pais <> c.nombre
  AND lower(translate(btrim(d.pais), 'ÁÉÍÓÚáéíóú', 'AEIOUaeiou')) = lower(translate(c.nombre, 'ÁÉÍÓÚáéíóú', 'AEIOUaeiou'));
UPDATE clientes x SET nacionalidad = c.nombre FROM nacionalidades c
WHERE x.nacionalidad <> c.nombre
  AND lower(translate(btrim(x.nacionalidad), 'ÁÉÍÓÚáéíóú', 'AEIOUaeiou')) = lower(translate(c.nombre, 'ÁÉÍÓÚáéíóú', 'AEIOUaeiou'));
UPDATE clientes x SET ocupacion = c.nombre FROM ocupaciones c
WHERE x.ocupacion <> c.nombre
  AND lower(translate(btrim(x.ocupacion), 'ÁÉÍÓÚáéíóú', 'AEIOUaeiou')) = lower(translate(c.nombre, 'ÁÉÍÓÚáéíóú', 'AEIOUaeiou'));

-- NOT VALID: un valor viejo que no coincida con el catálogo no impide migrar ni editar otros datos del cliente;
-- solo se exige al insertar o cambiar ese campo.
ALTER TABLE clientes ADD CONSTRAINT fk_clientes_nacionalidad
    FOREIGN KEY (nacionalidad) REFERENCES nacionalidades (nombre) ON UPDATE CASCADE NOT VALID;
ALTER TABLE clientes ADD CONSTRAINT fk_clientes_ocupacion
    FOREIGN KEY (ocupacion) REFERENCES ocupaciones (nombre) ON UPDATE CASCADE NOT VALID;
ALTER TABLE domicilios ADD CONSTRAINT fk_domicilios_pais
    FOREIGN KEY (pais) REFERENCES paises (nombre) ON UPDATE CASCADE NOT VALID;

-- Si no quedó ningún valor fuera del catálogo, las tres restricciones se validan por completo.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM clientes x WHERE NOT EXISTS (SELECT 1 FROM nacionalidades n WHERE n.nombre = x.nacionalidad)) THEN
        ALTER TABLE clientes VALIDATE CONSTRAINT fk_clientes_nacionalidad;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM clientes x WHERE x.ocupacion IS NOT NULL
                   AND NOT EXISTS (SELECT 1 FROM ocupaciones o WHERE o.nombre = x.ocupacion)) THEN
        ALTER TABLE clientes VALIDATE CONSTRAINT fk_clientes_ocupacion;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM domicilios d WHERE NOT EXISTS (SELECT 1 FROM paises p WHERE p.nombre = d.pais)) THEN
        ALTER TABLE domicilios VALIDATE CONSTRAINT fk_domicilios_pais;
    END IF;
END $$;
